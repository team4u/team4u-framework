package com.team4u.log.mask;

/**
 * 掩码脱敏类型定义
 */
public enum MaskType {
    /**
     * 姓名（如：周杰伦 -> 周*伦）
     */
    NAME,
    /**
     * 手机号（如：13812345678 -> 138****5678）
     */
    PHONE,
    /**
     * 身份证（如：440111199001011234 -> 440***********1234）
     */
    IDCARD,
    /**
     * 密码
     */
    PASSWORD,
    /**
     * 动态脱敏（预留，后续可结合配置中心支持）
     */
    DYNAMIC
}
